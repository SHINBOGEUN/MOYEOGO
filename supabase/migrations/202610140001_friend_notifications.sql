-- Persistent, recipient-owned friend notifications and private Expo push tokens.
-- Apply after 202610130001_friend_management.sql.

create table public.friend_notifications (
  id uuid primary key default gen_random_uuid(),
  recipient_user_id uuid not null references auth.users(id) on delete cascade,
  actor_user_id uuid not null references auth.users(id) on delete cascade,
  actor_nickname text not null,
  kind text not null check (kind in ('friend_request', 'friend_accepted')),
  source_request_id uuid not null,
  created_at timestamptz not null default now(),
  read_at timestamptz,
  constraint friend_notifications_one_per_transition unique (source_request_id, kind),
  constraint friend_notifications_distinct_accounts check (recipient_user_id <> actor_user_id)
);
create index friend_notifications_recipient_newest
  on public.friend_notifications (recipient_user_id, created_at desc);
create index friend_notifications_recipient_unread
  on public.friend_notifications (recipient_user_id, created_at desc) where read_at is null;

alter table public.friend_notifications enable row level security;
create policy friend_notifications_read_own on public.friend_notifications
  for select to authenticated using (recipient_user_id = (select auth.uid()));
revoke all on public.friend_notifications from public, anon, authenticated;
grant select on public.friend_notifications to authenticated;

-- The source row is generated by trusted friend RPCs. Keep its ID as an immutable
-- value so cancelling/removing a relationship does not erase notification history.
create or replace function public.record_friend_notification()
returns trigger language plpgsql security definer set search_path = '' as $$
declare notification_actor uuid; notification_recipient uuid; notification_kind text;
declare saved_nickname text;
begin
  if tg_op = 'INSERT' and new.status = 'pending' then
    notification_actor := new.requester_user_id;
    notification_recipient := new.addressee_user_id;
    notification_kind := 'friend_request';
  elsif tg_op = 'UPDATE' and old.status = 'pending' and new.status = 'accepted' then
    notification_actor := new.addressee_user_id;
    notification_recipient := new.requester_user_id;
    notification_kind := 'friend_accepted';
  else
    return new;
  end if;

  select coalesce(nullif(p.nickname, ''), '친구') into saved_nickname
    from public.profiles p where p.user_id = notification_actor;
  insert into public.friend_notifications
    (recipient_user_id, actor_user_id, actor_nickname, kind, source_request_id)
  values (notification_recipient, notification_actor, coalesce(saved_nickname, '친구'),
          notification_kind, new.id)
  on conflict (source_request_id, kind) do nothing;
  return new;
end;
$$;
create trigger friend_requests_record_notification
  after insert or update of status on public.friend_requests
  for each row execute function public.record_friend_notification();
revoke all on function public.record_friend_notification() from public, anon, authenticated;

create or replace function public.mark_my_friend_notification_read(notification_id uuid)
returns void language plpgsql security definer set search_path = '' as $$
begin
  if auth.uid() is null then raise exception 'not_authenticated'; end if;
  update public.friend_notifications set read_at = coalesce(read_at, now())
    where id = notification_id and recipient_user_id = auth.uid();
  if not found then raise exception 'notification_not_found'; end if;
end;
$$;
revoke all on function public.mark_my_friend_notification_read(uuid) from public, anon;
grant execute on function public.mark_my_friend_notification_read(uuid) to authenticated;

-- Keep devices private: even their owner uses narrow RPCs rather than exposing
-- push tokens through the table API or Realtime.
revoke all on public.user_devices from public, anon, authenticated;

create or replace function public.register_my_push_token(push_token text, platform text)
returns void language plpgsql security definer set search_path = '' as $$
declare current_user_id uuid := auth.uid();
begin
  if current_user_id is null then raise exception 'not_authenticated'; end if;
  if push_token is null or push_token !~ '^(Expo|Exponent)PushToken\[[A-Za-z0-9_-]{16,200}\]$'
     or char_length(push_token) > 256 then raise exception 'invalid_push_token'; end if;
  if platform not in ('ios', 'android') then raise exception 'invalid_platform'; end if;
  if not exists (select 1 from public.profiles p where p.user_id = current_user_id and p.notifications_enabled)
    then raise exception 'notifications_disabled'; end if;
  perform pg_advisory_xact_lock(hashtextextended('push-devices:' || current_user_id::text, 0));
  -- Expo tokens can remain the same when the account on one device changes.
  -- Reassigning that exact token prevents the previous account receiving pushes.
  insert into public.user_devices (user_id, push_token, platform, last_seen_at, disabled_at)
  values (current_user_id, push_token, platform, now(), null)
  on conflict (push_token) do update set user_id = excluded.user_id,
    platform = excluded.platform, last_seen_at = now(), disabled_at = null;
  -- Bound one account's fanout even if a client repeatedly rotates tokens.
  delete from public.user_devices d where d.id in (
    select old.id from public.user_devices old where old.user_id = current_user_id
      order by old.last_seen_at desc, old.id desc offset 10
  );
end;
$$;

create or replace function public.unregister_my_push_token(push_token text)
returns void language plpgsql security definer set search_path = '' as $$
begin
  if auth.uid() is null then raise exception 'not_authenticated'; end if;
  if push_token is null or push_token !~ '^(Expo|Exponent)PushToken\[[A-Za-z0-9_-]{16,200}\]$'
     or char_length(push_token) > 256 then raise exception 'invalid_push_token'; end if;
  -- The exact Expo token is held by this device. It may still belong to the
  -- previously signed-in account, especially when the new account disables
  -- notifications and therefore cannot register/reassign it first. Returning
  -- void for both present and absent tokens prevents ownership enumeration.
  delete from public.user_devices d where d.push_token = unregister_my_push_token.push_token;
end;
$$;
revoke all on function public.register_my_push_token(text, text) from public, anon;
revoke all on function public.unregister_my_push_token(text) from public, anon;
grant execute on function public.register_my_push_token(text, text) to authenticated;
grant execute on function public.unregister_my_push_token(text) to authenticated;

-- A webhook retry may invoke the Edge Function more than once. Claim the event
-- transactionally before making any external call. This gives at-most-once push
-- attempts per event; a network failure does not roll back the friend action.
create table public.friend_notification_push_attempts (
  notification_id uuid primary key references public.friend_notifications(id) on delete cascade,
  attempted_at timestamptz not null default now()
);
alter table public.friend_notification_push_attempts enable row level security;
revoke all on public.friend_notification_push_attempts from public, anon, authenticated;

create or replace function public.claim_friend_notification_push(notification_id uuid)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare claimed public.friend_notifications%rowtype;
declare active_tokens jsonb;
begin
  insert into public.friend_notification_push_attempts (notification_id)
    select n.id from public.friend_notifications n where n.id = claim_friend_notification_push.notification_id
    on conflict do nothing;
  if not found then return null; end if;

  select n.* into claimed from public.friend_notifications n
    where n.id = claim_friend_notification_push.notification_id;
  select coalesce(jsonb_agg(jsonb_build_object('token', d.push_token, 'platform', d.platform)), '[]'::jsonb)
    into active_tokens
    from public.user_devices d
    join public.profiles p on p.user_id = d.user_id
    where d.user_id = claimed.recipient_user_id and d.disabled_at is null
      and p.notifications_enabled;
  return jsonb_build_object('id', claimed.id, 'kind', claimed.kind,
    'actor_nickname', claimed.actor_nickname, 'source_request_id', claimed.source_request_id,
    'tokens', active_tokens);
end;
$$;
revoke all on function public.claim_friend_notification_push(uuid) from public, anon, authenticated;
grant execute on function public.claim_friend_notification_push(uuid) to service_role;

-- Cancellation and rejection can otherwise be used to resend a request and
-- generate unbounded pushes. Persisted notifications retain the rate history.
create or replace function public.send_friend_request(requested_friend_code text)
returns void language plpgsql security definer set search_path = '' as $$
declare current_user_id uuid := auth.uid(); target_user_id uuid;
begin
  if current_user_id is null then raise exception 'not_authenticated'; end if;
  select p.user_id into target_user_id from public.profiles p
    where upper(p.friend_code) = upper(btrim(requested_friend_code));
  if target_user_id is null then raise exception 'friend_not_found'; end if;
  if target_user_id = current_user_id then raise exception 'cannot_add_self'; end if;
  perform pg_advisory_xact_lock(hashtextextended('friend-request:' || current_user_id::text, 0));
  if exists (select 1 from public.friend_requests fr
    where least(fr.requester_user_id, fr.addressee_user_id) = least(current_user_id, target_user_id)
      and greatest(fr.requester_user_id, fr.addressee_user_id) = greatest(current_user_id, target_user_id)
      and fr.status = 'accepted') then raise exception 'already_friends'; end if;
  if exists (select 1 from public.friend_requests fr
    where fr.requester_user_id = target_user_id and fr.addressee_user_id = current_user_id
      and fr.status = 'pending') then raise exception 'incoming_request_exists'; end if;
  if (select count(*) from public.friend_notifications n
      where n.actor_user_id = current_user_id and n.recipient_user_id = target_user_id
        and n.kind = 'friend_request' and n.created_at > now() - interval '24 hours') >= 3
    or (select count(*) from public.friend_notifications n
      where n.actor_user_id = current_user_id and n.kind = 'friend_request'
        and n.created_at > now() - interval '24 hours') >= 30
    then raise exception 'friend_request_rate_limited'; end if;
  insert into public.friend_requests (requester_user_id, addressee_user_id)
    values (current_user_id, target_user_id);
exception when unique_violation then raise exception 'friend_request_exists';
end;
$$;
revoke all on function public.send_friend_request(text) from public, anon;
grant execute on function public.send_friend_request(text) to authenticated;

